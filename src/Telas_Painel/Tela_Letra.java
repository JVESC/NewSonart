    public void mostrarFaixa(Dados.Faixa faixa) {

    linhas.clear();
    linhaAtual = -1;

    if (destaqueAtual != null) {
        jTLetra.getHighlighter().removeHighlight(destaqueAtual);
        destaqueAtual = null;
    }

    jLTitulo.setText(faixa.titulo);
    jLArtista.setText(faixa.artista);

    String letra = faixa.letraSincronizada;

    if (letra == null || letra.isBlank()) {
        jTLetra.setText("Letra não disponível.");
        return;
    }

    Pattern padrao = Pattern.compile(
            "\\[(\\d{2,}):(\\d{2})(?:\\.(\\d{2,3}))?\\]"
    );

    StringBuilder textoCompleto = new StringBuilder();

    for (String linha : letra.split("\\R")) {

        Matcher matcher = padrao.matcher(linha);

        List<Double> tempos = new ArrayList<>();

        while (matcher.find()) {

            int minutos = Integer.parseInt(matcher.group(1));
            int segundos = Integer.parseInt(matcher.group(2));

            String fracao = matcher.group(3);

            double tempo = minutos * 60 + segundos;

            if (fracao != null) {
                tempo += Integer.parseInt(fracao)
                        / (fracao.length() == 2 ? 100.0 : 1000.0);
            }

            tempos.add(tempo);
        }

        String texto = matcher.replaceAll("").trim();

        // Ignora informações de identificação do arquivo LRC
        texto = texto.replaceAll("\\[[a-zA-Z]+:.*?\\]", "").trim();

        if (texto.isBlank()) {
            continue;
        }

        if (tempos.isEmpty()) {
            LinhaLetra item = new LinhaLetra(-1, texto);
            linhas.add(item);
        } else {
            for (double tempo : tempos) {
                linhas.add(new LinhaLetra(tempo, texto));
            }
        }
    }

    // Ordena os versos pelo tempo
    linhas.removeIf(linha -> linha.tempo < 0);

    linhas.sort(Comparator.comparingDouble(linha -> linha.tempo));

    for (LinhaLetra linha : linhas) {
        linha.inicio = textoCompleto.length();
        textoCompleto.append(linha.texto).append("\n");
        linha.fim = textoCompleto.length() - 1;
    }

    jTLetra.setText(textoCompleto.toString());
    jTLetra.setCaretPosition(0);
}
    public void atualizarTempo(double tempo) {

    int novaLinha = -1;

    for (int i = 0; i < linhas.size(); i++) {

        if (linhas.get(i).tempo <= tempo) {
            novaLinha = i;
        } else {
            break;
        }
    }

    if (novaLinha == linhaAtual || novaLinha < 0) {
        return;
    }

    linhaAtual = novaLinha;

    if (destaqueAtual != null) {
        jTLetra.getHighlighter().removeHighlight(destaqueAtual);
    }

    LinhaLetra linha = linhas.get(linhaAtual);

    try {
        destaqueAtual = jTLetra.getHighlighter().addHighlight(
                linha.inicio,
                linha.fim,
                pintor
        );

        // Acompanha o verso atual na tela
        jTLetra.setCaretPosition(linha.inicio);

    } catch (javax.swing.text.BadLocationException ex) {
        ex.printStackTrace();
    }
}
    
    
    
    
    
    
